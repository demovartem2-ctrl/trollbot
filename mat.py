def is_mat(text: str) -> bool:
    if not text:
        return False
    low = text.lower().replace("ё", "е")
    low = re.sub(r'[^\w\s]', '', low)
    
    for root in MAT_ROOTS:
        if root.replace("ё", "е") in low:
            return True
    return False

def make_reply(name: str) -> str:
    # Собираем монстра из 5 частей
    prefix = random.choice(PREFIXES).format(name=name)
    noun = random.choice(NOUNS)
    extension = random.choice(INSULT_EXTENSIONS) if random.random() > 0.4 else "" # 60% шанс на добавление унижения
    action = random.choice(ACTIONS)
    tail = random.choice(TAILS)
    
    # Склеиваем
    parts = [prefix, noun]
    if extension:
        parts.append(f"({extension})")
    parts.append(action + tail)
    
    insult = " ".join(parts)
    
    # Если хвоста нет, добавляем эмодзи
    if not tail:
        insult += " " + random.choice(["🤬", "🖕", "💩", "🤡", "🐖", "🔥", "😡", "🤮", "☠️", "⚰️"])
        
    return insult
