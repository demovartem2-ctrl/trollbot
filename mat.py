def make_reply(name: str) -> str:
    prefix = random.choice(PREFIXES).format(name=name)
    noun = random.choice(NOUNS)
    extension = random.choice(INSULT_EXTENSIONS) if random.random() > 0.4 else ""
    action = random.choice(ACTIONS)
    tail = random.choice(TAILS)
    
    parts = [prefix, noun]
    if extension:
        parts.append(f"({extension})")
    parts.append(action + tail)
    
    insult = " ".join(parts)
    if not tail:
        insult += " " + random.choice(["🤬", "🖕", "💩", "🤡", "🐖", "🔥", "😡", "🤮", "☠️", "⚰️"])
    return insult
